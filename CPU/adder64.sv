`timescale 1ns/10ps

module adder64 (A, B, SUB, CO, S);
	input logic[63:0] A, B;
	input logic SUB;
	output logic[63:0] S;
	output logic CO;
	logic[64:0] BWIRE, CWIRE;
	
	assign CWIRE[0] = SUB;
	assign CO = CWIRE[64];
	
	genvar i;
	generate
	 for (i = 0; i < 64; i++) begin : genAdd
		xor #50 xors (BWIRE[i], B[i], SUB);
		fullAdder ex(A[i], BWIRE[i], CWIRE[i], CWIRE[i + 1], S[i]);
	 end
	endgenerate
	
endmodule 

